#!/bin/bash
# farecli の全機能テストスクリプト

source ../all/start.sh

echo "=========================================="
echo "Test 1: カンマ区切り経路"
echo "=========================================="
./farecli "東京,東海道線,横浜" | grep -E "(東京 ->|営業キロ|運賃)"

echo ""
echo "=========================================="
echo "Test 2: 個別指定経路（奇数個）"
echo "=========================================="
./farecli 東京 東海道線 横浜 | grep -E "(東京 ->|営業キロ|運賃)"

echo ""
echo "=========================================="
echo "Test 3: 自動経路検索（偶数個）"
echo "=========================================="
./farecli 東京 名古屋 | grep -E "(東京|営業キロ|運賃)" | head -5

echo ""
echo "=========================================="
echo "Test 4: JSON出力"
echo "=========================================="
./farecli -j 東京 東海道線 横浜 | grep -o '"fare":[0-9]*'

echo ""
echo "=========================================="
echo "Test 5: ファイル入力"
echo "=========================================="
./farecli -f sample_routes.txt | grep -E "^(Line|東京|新大阪|営業キロ)" | head -10

echo ""
echo "=========================================="
echo "すべてのテストが完了しました"
echo "=========================================="
